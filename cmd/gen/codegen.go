package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"
)

var goInitialisms = map[string]string{
	"ID":   "ID",
	"URL":  "URL",
	"URI":  "URI",
	"API":  "API",
	"HTML": "HTML",
	"JSON": "JSON",
	"XML":  "XML",
	"HTTP": "HTTP",
}

// goName converts a JSON property name to an exported Go identifier.
// Examples: "id" → "ID", "wordCount" → "WordCount", "basic-science" → "BasicScience"
func goName(name string) string {
	parts := splitIdent(name)
	var b strings.Builder
	for _, p := range parts {
		up := strings.ToUpper(p)
		if initialism, ok := goInitialisms[up]; ok {
			b.WriteString(initialism)
		} else if len(p) > 0 {
			b.WriteString(strings.ToUpper(p[:1]))
			b.WriteString(p[1:])
		}
	}
	return b.String()
}

// splitIdent splits on hyphens, underscores, and camelCase boundaries.
func splitIdent(s string) []string {
	var parts []string
	var cur strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if r == '_' || r == '-' {
			if cur.Len() > 0 {
				parts = append(parts, cur.String())
				cur.Reset()
			}
		} else if i > 0 && unicode.IsUpper(r) && unicode.IsLower(runes[i-1]) {
			parts = append(parts, cur.String())
			cur.Reset()
			cur.WriteRune(r)
		} else {
			cur.WriteRune(r)
		}
	}
	if cur.Len() > 0 {
		parts = append(parts, cur.String())
	}
	return parts
}

func isNullable(s *Schema) bool {
	for _, t := range s.Type.Values {
		if t == "null" {
			return true
		}
	}
	return false
}

func primaryType(s *Schema) string {
	for _, t := range s.Type.Values {
		if t != "null" {
			return t
		}
	}
	return ""
}

func goScalarType(jsonType string) string {
	switch jsonType {
	case "string":
		return "string"
	case "integer":
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	default:
		return "any"
	}
}

// goFieldType returns the Go type string for a single schema property.
// parentTypeName is used to build enum type names (e.g. "Category" + "Kind" → "CategoryKind").
func goFieldType(fieldName string, s *Schema, parentTypeName string) string {
	nullable := isNullable(s)
	prim := primaryType(s)

	if len(s.Enum) > 0 && prim == "string" {
		t := parentTypeName + goName(fieldName)
		if nullable {
			return "*" + t
		}
		return t
	}

	switch prim {
	case "string", "integer", "number", "boolean":
		t := goScalarType(prim)
		if nullable {
			return "*" + t
		}
		return t
	}

	return "any"
}

func jsonTag(propName string, required bool) string {
	if required {
		return "`json:\"" + propName + "\"`"
	}
	return "`json:\"" + propName + ",omitempty\"`"
}

func sortedKeys(m map[string]*Schema) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// generateCategory generates Go source for the Category schema.
// Handles: scalar fields, nullable fields, and string enums.
func generateCategory(s *Schema) string {
	var b strings.Builder
	required := toSet(s.Required)

	for _, propName := range sortedKeys(s.Properties) {
		prop := s.Properties[propName]
		if len(prop.Enum) > 0 && primaryType(prop) == "string" {
			typeName := "Category" + goName(propName)
			b.WriteString(fmt.Sprintf("type %s string\n\n", typeName))
			b.WriteString("const (\n")
			for _, v := range prop.Enum {
				val := fmt.Sprintf("%v", v)
				b.WriteString(fmt.Sprintf("\t%s%s %s = %q\n", typeName, goName(val), typeName, val))
			}
			b.WriteString(")\n\n")
		}
	}

	b.WriteString("type Category struct {\n")
	for _, propName := range sortedKeys(s.Properties) {
		prop := s.Properties[propName]
		b.WriteString(fmt.Sprintf("\t%s %s %s\n",
			goName(propName),
			goFieldType(propName, prop, "Category"),
			jsonTag(propName, required[propName]),
		))
	}
	b.WriteString("}\n\n")

	return b.String()
}

func toSet(ss []string) map[string]bool {
	m := make(map[string]bool, len(ss))
	for _, s := range ss {
		m[s] = true
	}
	return m
}

// buildModel assembles the full model/model.go source and formats it with gofmt.
func buildModel(schemas map[string]*Schema) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/gen. DO NOT EDIT.\n\n")
	b.WriteString("package model\n\n")

	if cat, ok := schemas["Category"]; ok {
		b.WriteString(generateCategory(cat))
	}

	// Stubs — replaced in later iterations
	b.WriteString("type Product struct{}\n\n")
	b.WriteString("type Article struct{}\n")

	return format.Source([]byte(b.String()))
}
